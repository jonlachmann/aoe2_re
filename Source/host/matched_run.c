/*
 * matched_run.c - the run step for the matched-only boot executable.
 *
 * The lifted host's run step starts the CRT entry (0x600281) through the
 * dispatch table. That CRT startup is library code and not matched, so this
 * build bypasses it and calls the game's WinMain at 0x47AE20 directly, with
 * the four WinMain arguments the CRT startup would pass. It goes through
 * hle_call_guest so the call happens on the guest stack with the guest
 * register file, exactly as a dispatch entry would.
 *
 * The first checkpoint is measured here: with WinMain still unmatched the
 * dispatch entry is a stub, so the call returns immediately and the harness
 * prints the VA that has to be matched next.
 */
#define _XOPEN_SOURCE 700
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

#include "win32hle.h"
#include "matched_guest_image.h"

/* Sorted dispatch table the win32hle lookup binary-searches. */
extern const recomp_dispatch_entry_t recomp_dispatch_table[];
extern const uint32_t recomp_dispatch_count;

/* Import-dispatch layer + WIP-body probe (Source/host/matched_imports.cpp). */
extern void InstallMatchedImports(void);
extern int matched_langtest(void);
extern int matched_winmain(void);

/* WinMain's entry VA in the reference image (PE entry 0x600281 calls it). */
#define MATCHED_BOOT_WINMAIN_VA 0x0047AE20u

/* Placeholder dispatch target until 0x47AE20 has a matched body. It records
 * the reached VA and returns 0 so the harness can report the checkpoint. */
static void matched_winmain_stub(void)
{
    fprintf(stderr, "[matched boot] checkpoint: WinMain VA 0x%08X reached, "
                    "no matched body yet (dispatch stub)\n",
            MATCHED_BOOT_WINMAIN_VA);
    g_eax = 0;
}

/* Table is generated by Scripts/build_matched_boot.sh; the stub above is the
 * entry it points at. Keeping the table in this TU avoids a separate object. */
const recomp_dispatch_entry_t recomp_dispatch_table[] = {
    { MATCHED_BOOT_WINMAIN_VA, matched_winmain_stub }
};
const uint32_t recomp_dispatch_count = 1;

uint32_t matched_recomp_host_run(void)
{
    /* hInstance = image base (PE ImageBase 0x400000), hPrevInstance = 0,
     * lpCmdLine = the guest command line set by the host, nCmdShow = 1. The
     * CRT startup reads the real command line from GetCommandLineA(); the
     * host harness already installed it through hle_set_command_line, and the
     * guest image holds it at the address the shim returns. Passing 0 here is
     * the empty-line case the game tolerates when it is started with no args. */
    /* Matched bodies dereference guest VAs through ADDR; load and sync the
     * PE-backed guest image before any matched body can run. */
    const char* pe = getenv("AOE_BIN");
    if (pe != 0 && LoadGuestImage(pe) == 0)
    {
        SyncGuestGlobals();
        fprintf(stderr, "[matched boot] guest image mapped (base VA 0x400000,"
                        " %ld bytes); g_* globals synced from it\n",
                (long)g_matched_image_size);
    }

    /* Install native trampolines over the raw IAT words in the generated g_*
     * slots so matched/WIP bodies can call imports through the win32hle shims. */
    InstallMatchedImports();

    /* Prove the import layer on the WIP language-init body 0x47B620 before
     * WinMain itself has a matched body. */
    matched_langtest();

    fprintf(stderr, "[matched boot] calling the native WinMain body"
                    " 0x%08X (hInstance=0x400000, hPrev=0, cmdline=0, nShow=1)\n",
            MATCHED_BOOT_WINMAIN_VA);
    uint32_t r = (uint32_t)matched_winmain();
    fprintf(stderr, "[matched boot] native WinMain body returned 0x%08X\n", r);
    return r;
}
