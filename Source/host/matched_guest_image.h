// Native guest image for the matched-only build.
//
// The matched bodies address guest data two ways: direct symbol references to
// the generated `g_*` arrays, and guest VA constants passed through ADDR().
// This module maps one contiguous image covering the guest data range
// [0x400000, 0x800000) and fills it with the reference binary's section bytes,
// so ADDR() resolves a guest VA the same way the binary does. SyncGuestGlobals
// then copies each `g_*` array's bytes from the image, guaranteeing symbol
// contents and image contents are identical.
#pragma once

#include <stddef.h>

extern "C" char* g_matched_image;      // host address of guest VA 0x400000
extern "C" long g_matched_image_size;  // bytes covered
extern "C" long g_matched_base;        // host address of guest VA 0

// Load the PE file at `path` into the image. Returns 0 on success and sets
// g_matched_image/g_matched_image_size/g_matched_base.
int LoadGuestImage(const char* path);

// Copy every generated g_* array from the image (generated by the build).
void SyncGuestGlobals();
