#!/usr/bin/env python3
"""Turn an aoe_boot --phases TSV (phase, order, va, count) into docs/call_phases/ (one file per phase).

Names come from MATCH_FUNC/WIP_FUNC sites in Source/ and docs/symbol_map.md.
Functions replaced by strong host overrides never enter RECOMP_ENTER and so
never appear. CRT-band functions (0x5F0000-0x610000) and LIBRARY_FUNC sites
are library code (docs/matching.md): listed apart, not counted as left to match.
  ./venv/bin/python Scripts/phase_report.py build/boot/phases.tsv
"""
import re, sys, pathlib

R = pathlib.Path(__file__).resolve().parent.parent
names, status = {}, {}
for f in (R / "Source").rglob("*.cpp"):
    lines = f.read_text(errors="replace").splitlines()
    for i, l in enumerate(lines):
        m = re.match(r"(MATCH|WIP|LIBRARY)_FUNC\(0x([0-9A-Fa-f]+)\)", l)
        if m and i + 1 < len(lines):
            va = int(m.group(2), 16)
            status[va] = m.group(1)
            n = re.search(r"([\w:~]+_[0-9A-Fa-f]{6})\s*\(", lines[i + 1])
            if n: names[va] = n.group(1)
for m in re.finditer(r"`([\w:]+)` \| `sub_([0-9A-F]+)`", (R / "docs/symbol_map.md").read_text()):
    names.setdefault(int(m.group(2), 16), m.group(1))

lib = lambda va: status.get(va) == "LIBRARY" or 0x5F0000 <= va < 0x610000

phases = {}
for line in open(sys.argv[1]):
    ph, order, va, cnt = line.split("\t")
    phases.setdefault(ph, []).append((int(va, 16), int(cnt)))

D = R / "docs/call_phases"
D.mkdir(exist_ok=True)
first = {}
for ph, rows in phases.items():
    for va, _ in rows: first.setdefault(va, ph)
idx = ["# Call phases: boot -> main menu -> Random Map match", "",
       "Generated by `Scripts/phase_report.py` from an `aoe_boot --phases` run "
       "(see docs/bringup_log.md, 2026-11-25). One file per phase lists every "
       "function called in it, split into left-to-match and matched "
       "(`MATCH_FUNC` in Source/); CRT/library code is listed apart. Raw data: `data/call_phases.tsv`.", "",
       "| phase | called | new in phase | matched | WIP | left to match | library |", "|---|---|---|---|---|---|---|"]
row = lambda i, va, c: (f"| {i} | `sub_{va:06X}` | {c} | {status.get(va, '')} | "
                        f"{first[va]} | {names.get(va, '')} |")
head = ["| # | function | count | status | first seen in | name |", "|---|---|---|---|---|---|"]
for ph, rows in phases.items():
    done = [(i, va, c) for i, (va, c) in enumerate(rows) if status.get(va) == "MATCH"]
    left = [(i, va, c) for i, (va, c) in enumerate(rows) if status.get(va) != "MATCH" and not lib(va)]
    libs = [(i, va, c) for i, (va, c) in enumerate(rows) if status.get(va) != "MATCH" and lib(va)]
    new = sum(first[va] == ph for va, _ in rows)
    wip = sum(status.get(va) == "WIP" for va, _ in rows)
    idx.append(f"| [{ph}]({ph}.md) | {len(rows)} | {new} | {len(done)} | {wip} | {len(left)} | {len(libs)} |")
    out = [f"# {ph}", "",
           f"{len(rows)} functions called ({new} first seen in this phase): "
           f"{len(done)} matched, {len(left)} left to match ({wip} of them WIP), "
           f"{len(libs)} CRT/library. "
           "`#` is first-entry order within the phase; `count` is entries during it.", "",
           f"## Left to match ({len(left)})", ""] + head + [row(*r) for r in left] + \
          ["", f"## Matched ({len(done)})", ""] + head + [row(*r) for r in done] + \
          ["", f"## CRT / library ({len(libs)})", ""] + head + [row(*r) for r in libs]
    (D / f"{ph}.md").write_text("\n".join(out) + "\n")
(D / "README.md").write_text("\n".join(idx) + "\n")
print(f"wrote {D}: {len(phases)} phases, {len(first)} distinct functions")
