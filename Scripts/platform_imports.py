"""Map every PE import to the game functions that use it -> docs/platform_imports.md.

An import is "used" by a function when one of its instructions references the
IAT slot (call [iat], jmp [iat], mov reg,[iat]) or calls an import thunk
(a `jmp [iat]` stub, e.g. dplayx's ordinals at 0x5ECE26..0x5ECE5C).
Function boundaries come from data/disasm32_catalog.json.

Usage: ./venv/bin/python Scripts/platform_imports.py
"""
import json
import os
from collections import defaultdict

import capstone
import pefile

EXE = os.environ.get("AOE_BIN") or "reference/AOE2.EXE"
OUT = "docs/platform_imports.md"

# What an SDL3 (or other portable) host would put behind each DLL.
SEAM = {
    "dplayx.dll": "net (SDL3_net / sockets)", "wsock32.dll": "net (SDL3_net / sockets)",
    "ddraw.dll": "video (SDL3 render/surface)", "gdi32.dll": "video (SDL3 render/surface)",
    "dsound.dll": "audio (SDL3 audio)", "winmm.dll": "audio/timing (SDL3 audio/timer)",
    "msvfw32.dll": "video playback (AVI)", "user32.dll": "window/input (SDL3 video/events)",
    "dinput.dll": "input (SDL3 events)", "advapi32.dll": "registry (config file)",
    "version.dll": "file version (stub)", "kernel32.dll": "OS/CRT (libc / SDL3 filesystem/thread)",
    "ole32.dll": "COM (stub)", "comctl32.dll": "UI controls", "shell32.dll": "shell (stub)",
    "imm32.dll": "IME (SDL3 text input)", "ebueula.dll": "EULA (stub)",
}

# Ordinal-only exports, by their documented names.
ORDINALS = {
    "dplayx.dll": {1: "DirectPlayCreate", 2: "DirectPlayEnumerateA", 4: "DirectPlayLobbyCreateA"},
    "dsound.dll": {1: "DirectSoundCreate"},
}


def main():
    pe = pefile.PE(EXE)
    base = pe.OPTIONAL_HEADER.ImageBase
    iat = {}  # slot VA -> (dll, name)
    for e in pe.DIRECTORY_ENTRY_IMPORT:
        dll = e.dll.decode().lower()
        for i in e.imports:
            iat[i.address] = (dll, i.name.decode() if i.name else
                              f"#{i.ordinal} {ORDINALS.get(dll, {}).get(i.ordinal, '')}".strip())

    cat = json.load(open("data/disasm32_catalog.json"))["functions"]
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    md.detail = True

    def slots(insn):
        for op in insn.operands:
            if op.type == capstone.x86.X86_OP_MEM and op.mem.base == 0 and op.mem.index == 0 \
                    and op.mem.disp in iat:
                yield op.mem.disp

    # pass 1: thunks (a lone jmp [iat])
    thunk = {}
    code = {}
    for f in cat:
        code[f["address"]] = list(md.disasm(pe.get_data(f["address"] - base, f["size"]), f["address"]))
        ins = code[f["address"]]
        if len(ins) == 1 and ins[0].mnemonic == "jmp":
            for s in slots(ins[0]):
                thunk[f["address"]] = s

    users = defaultdict(set)  # slot -> caller function VAs
    for f in cat:
        if f["address"] in thunk:
            continue
        for insn in code[f["address"]]:
            for s in slots(insn):
                users[s].add(f["address"])
            if insn.mnemonic in ("call", "jmp") and insn.operands \
                    and insn.operands[0].type == capstone.x86.X86_OP_IMM \
                    and insn.operands[0].imm in thunk:
                users[thunk[insn.operands[0].imm]].add(f["address"])

    by_dll = defaultdict(list)
    for s, (dll, name) in iat.items():
        by_dll[dll].append((name, s, sorted(users.get(s, ()))))

    out = ["# Platform imports -> game call sites",
           "",
           "Generated by `Scripts/platform_imports.py` from the PE import table and",
           "`data/disasm32_catalog.json`. Each row lists the game functions that touch",
           "the import (directly or through a `jmp [iat]` thunk). These are the seams",
           "a portable host (SDL3) replaces: either the shim in win32hle, or the",
           "caller function in `Source/<module>/` once it is reconstructed.",
           "",
           "Only the entry points show up here. DirectDraw, DirectSound and DirectPlay",
           "are COM: after the `*Create` call, every method is a `call [reg+N]` through",
           "a vtable, so the functions listed against `*Create` are where the object is",
           "made, not every user of it.",
           "",
           "| DLL | seam | imports | distinct callers |",
           "|---|---|---|---|"]
    for dll in sorted(by_dll):
        callers = set().union(*(set(u) for _, _, u in by_dll[dll]))
        out.append(f"| {dll} | {SEAM.get(dll, '?')} | {len(by_dll[dll])} | {len(callers)} |")
    for dll in sorted(by_dll):
        out += ["", f"## {dll}", "", "| import | IAT | callers |", "|---|---|---|"]
        for name, s, u in sorted(by_dll[dll]):
            cs = ", ".join(f"`{a:06X}`" for a in u[:12]) + (f" (+{len(u) - 12})" if len(u) > 12 else "")
            out.append(f"| {name} | `{s:06X}` | {cs or '-'} |")
    open(OUT, "w").write("\n".join(out) + "\n")
    print(f"wrote {OUT}: {len(iat)} imports, {len(thunk)} thunks")


if __name__ == "__main__":
    main()
